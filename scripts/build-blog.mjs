// Reads blog/*.md (front matter + Markdown) and writes src/content/blog/posts.generated.ts, so the blog pages,
// the nav, the RSS feed, and the Ask assistant all read the same posts without touching the filesystem at runtime.
// Runs before build and dev; the output is committed too.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Marked } from 'marked'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'blog')
const outDir = join(root, 'src/content/blog')
mkdirSync(outDir, { recursive: true })

const slugify = (s) => s.toLowerCase().replace(/<[^>]+>/g, '').replace(/&[a-z]+;/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

function frontMatter(src, file) {
  const m = src.match(/^---\s*\n([\s\S]*?)\n---\s*\n?/)
  if (!m) throw new Error(`blog/${file}: missing the --- header (see blog/README.md)`)
  const meta = {}
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':')
    if (i < 0 || !line.trim()) continue
    meta[line.slice(0, i).trim()] = line.slice(i + 1).trim().replace(/^["']|["']$/g, '')
  }
  return { meta, body: src.slice(m[0].length) }
}

const posts = []
const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.md') && f.toLowerCase() !== 'readme.md') : []
for (const file of files) {
  const slug = file.replace(/\.md$/, '')
  if (!/^[a-z0-9-]+$/.test(slug)) throw new Error(`blog/${file}: use lowercase letters, numbers, and dashes in the file name`)
  const { meta, body } = frontMatter(readFileSync(join(dir, file), 'utf8'), file)
  if (!meta.title || !meta.date) throw new Error(`blog/${file}: needs a title and a date`)
  if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date)) throw new Error(`blog/${file}: date must look like 2026-10-20`)
  const draft = /^(true|yes)$/i.test(meta.draft ?? '')
  const headings = []
  const marked = new Marked({ gfm: true })
  marked.use({
    renderer: {
      heading({ tokens, depth }) {
        const text = this.parser.parseInline(tokens)
        const id = slugify(text)
        if (depth === 2) headings.push({ id, text: text.replace(/<[^>]+>/g, '') })
        return `<h${depth} id="${id}">${text}</h${depth}>\n`
      },
      image({ href, title, text }) {
        return `<figure><img src="${href}" alt="${text ?? ''}" loading="lazy" decoding="async" />${title ? `<figcaption>${title}</figcaption>` : text ? `<figcaption>${text}</figcaption>` : ''}</figure>`
      },
      link({ href, title, tokens }) {
        const ext = /^https?:/.test(href)
        return `<a href="${href}"${title ? ` title="${title}"` : ''}${ext ? ' target="_blank" rel="noopener noreferrer"' : ''}>${this.parser.parseInline(tokens)}</a>`
      },
    },
  })
  const html = marked.parse(body)
  const words = body.split(/\s+/).filter(Boolean).length
  posts.push({
    slug,
    title: meta.title,
    date: meta.date,
    summary: meta.summary ?? '',
    cover: meta.cover || null,
    tags: (meta.tags ?? '').split(',').map((t) => t.trim()).filter(Boolean),
    draft,
    minutes: Math.max(1, Math.round(words / 230)),
    headings,
    html,
    text: body.trim(),
  })
}
posts.sort((a, b) => b.date.localeCompare(a.date))
const live = posts.filter((p) => !p.draft)

writeFileSync(
  join(outDir, 'posts.generated.ts'),
  `// Generated by scripts/build-blog.mjs from blog/*.md. Do not edit by hand.\n\nimport type { Post } from './types'\n\nexport const POSTS: Post[] = ${JSON.stringify(live, null, 2)}\n`,
)
console.log(`blog: ${live.length} posts${posts.length > live.length ? `, ${posts.length - live.length} drafts` : ''}`)
