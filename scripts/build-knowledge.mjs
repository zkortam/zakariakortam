// Bundles src/knowledge/*.md into src/lib/ask/knowledge.generated.ts at build time,
// so the API route never touches the filesystem at request time.
// Runs as `prebuild`; the output is committed too, so a build that skips npm hooks still works.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'src/knowledge')
const out = join(root, 'src/lib/ask/knowledge.generated.ts')

const docs = readdirSync(dir)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((f) => ({ id: f.replace(/\.md$/, ''), text: readFileSync(join(dir, f), 'utf8').trim() }))

const banned = /[–—]/
for (const d of docs) {
  if (banned.test(d.text)) throw new Error(`src/knowledge/${d.id}.md contains an em or en dash`)
}

const body = `// Generated by scripts/build-knowledge.mjs from src/knowledge/*.md. Do not edit by hand.\n\nexport const KNOWLEDGE_DOCS: { id: string; text: string }[] = ${JSON.stringify(docs, null, 2)}\n`
writeFileSync(out, body)

const chars = docs.reduce((n, d) => n + d.text.length, 0)
console.log(`knowledge: ${docs.length} docs, ${chars} chars, about ${Math.round(chars / 4)} tokens`)
